// library2d.js: Bench EVERY section and write js/sectionStats.js, the table
// the course builder reads.
//
//   node MarbleRush2D/tools/library2d.js [--races 40]
//
// For each section, from a fair start (The Draw) straight into it:
//   swaps   pairs of marbles that swapped order through it, of 10
//   grow    how much it spread the field, seconds (out - in)
//   secs    time through
//   nudge   share of races that needed a stuck-marble nudge
// This is the "intelligence" in the course builder: it is measured, not
// guessed, and re-running this after changing a section keeps it honest.
//
//   --only a,b   re-bench just these sections and keep every other row.
import { writeFileSync } from 'node:fs';
import { SECTIONS } from '../js/track2d.js';
import { SECTION_STATS } from '../js/sectionStats.js';
import { recordRace } from './drama2d.js';

const argv = process.argv.slice(2);
const i = argv.indexOf('--races');
const N = i >= 0 ? +argv[i + 1] : 40;
const oi = argv.indexOf('--only');
const only = oi >= 0 ? new Set(argv[oi + 1].split(',')) : null;
const K = 5;
const stats = only ? { ...SECTION_STATS } : {};
for (const sec of SECTIONS) {
  if (sec.id === 'draw' || sec.showcase || (only && !only.has(sec.id))) continue;
  let swaps = 0, grow = 0, secs = 0, n = 0, bad = 0;
  for (let r = 0; r < N; r++) {
    const R = recordRace('lib' + sec.id + r, { only: ['draw', sec.id] });
    if (R.nudges) bad++;
    const a = R.cross[1], b = R.cross[2];
    const live = [...Array(K).keys()].filter(k => a[k] !== null && b[k] !== null);
    if (live.length < 2) continue;
    const oa = live.slice().sort((x, y) => a[x] - a[y]), ob = live.slice().sort((x, y) => b[x] - b[y]);
    const pa = new Map(oa.map((v, k) => [v, k])), pb = new Map(ob.map((v, k) => [v, k]));
    for (let x = 0; x < live.length; x++) for (let y = x + 1; y < live.length; y++) {
      if ((pa.get(live[x]) - pa.get(live[y])) * (pb.get(live[x]) - pb.get(live[y])) < 0) swaps++;
    }
    const sp = (t) => Math.max(...live.map(k => t[k])) - Math.min(...live.map(k => t[k]));
    grow += sp(b) - sp(a);
    secs += live.reduce((acc, k) => acc + b[k] - a[k], 0) / live.length;
    n++;
  }
  stats[sec.id] = { swaps: +(swaps / n).toFixed(2), grow: +(grow / n).toFixed(2), secs: +(secs / n).toFixed(1), nudge: +(bad / N).toFixed(3) };
  process.stderr.write(`${sec.id.padEnd(14)} ${JSON.stringify(stats[sec.id])}\n`);
}
const out = `// GENERATED by tools/library2d.js (${N} races per section). Do not edit by hand:\n` +
  `// re-run the tool after changing a section.\n` +
  `export const SECTION_STATS = ${JSON.stringify(stats, null, 1)};\n`;
writeFileSync(new URL('../js/sectionStats.js', import.meta.url), out);
console.log(`wrote js/sectionStats.js, ${Object.keys(stats).length} sections`);
